import { describe, expect, it } from "vitest";
import { explicitResultQuote } from "./result-quote";

describe("explicit desired-result quote recovery", () => {
  it.each([
    ["На ферме график полива ведут в бумажной тетради. Агроном хочет видеть запланированные и выполненные поливы на общей доске. Исторической цифровой базы нет.", "Агроном хочет видеть запланированные и выполненные поливы на общей доске."],
    ["Музей вручную собирает отзывы. Нужен отчёт с распределением отзывов по темам.", "Нужен отчёт с распределением отзывов по темам."],
    ["Заявки теряются в переписке. Хотим получить прототип приложения для регистрации заявок.", "Хотим получить прототип приложения для регистрации заявок."],
    ["Для центра требуется каталог доступных секций!", "Для центра требуется каталог доступных секций!"],
  ])("copies a complete unchanged source sentence: %s", (source, expected) => {
    expect(explicitResultQuote(source)).toBe(expected);
    expect(source).toContain(expected);
  });

  it.each([
    "Агроном не хочет видеть поливы на общей доске.",
    "Нам не нужна панель заказов.",
    "Не планируем создавать каталог, хотим изучить проблему.",
    "Если найдём данные, нужен отчёт по продажам.",
    "Нужна ли отдельная страница для клиентов?",
    "Возможно, нужна таблица заявок.",
    "Нужен каталог. Позже передумали и отказались от этой идеи.",
    "Раньше хотели каталог. Сейчас он не нужен.",
    "Нужен каталог или отчёт, выбор пока не сделали.",
    "Нужен каталог. Нужна отдельная панель администратора.",
    "Есть доска задач, хотим уменьшить потери времени.",
    "Диспетчер хочет понять, почему теряются заявки.",
    "Каждый вечер остаётся выпечка. Хотим уменьшить списания.",
    "Нужна консультация по существующему каталогу.",
    "Нужно досконально изучить процесс и сократить расходы.",
    "Нужна ботаническая экспертиза растения.",
  ])("does not guess a deliverable from ambiguity, rejection or a general goal: %s", (source) => {
    expect(explicitResultQuote(source)).toBeUndefined();
  });
});
